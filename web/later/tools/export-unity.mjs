// Writes the Unity version's copy of data.js (Assets/Later/Scripts/Core/LaterData.g.cs), so both versions
// read the same numbers and text, and the rounds its tests replay to prove both versions play the same.
// Run `npm run export-unity` after changing data.js or round.js.
// --check compares instead of writing, and exits 1 if anything on disk is stale.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import * as D from "../src/data.js";
import { createRound, stepRound } from "../src/round.js";
import { dodgeTarget, chaseTarget } from "../tests/bots.js";

const repo = fileURLToPath(new URL("../../../", import.meta.url));
const check = process.argv.includes("--check");

const num = n => {
  if (typeof n !== "number" || !Number.isFinite(n)) throw new Error(`not a number: ${n}`);
  return String(n);
};
const int = n => {
  if (!Number.isInteger(n)) throw new Error(`not an integer: ${n}`);
  return String(n);
};
const str = s => {
  if (typeof s !== "string") throw new Error(`not a string: ${s}`);
  return `"${s.replace(/[\\"]/g, c => "\\" + c).replace(/[\x00-\x1f]/g, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`)}"`;
};
const keys = (o, allowed, what) => {
  for (const k of Object.keys(o)) if (!allowed.includes(k)) throw new Error(`${what}: don't know how to write "${k}"`);
};
const list = (xs, f) => xs.map(f).join(", ");
const dict = (type, o, f) => `new Dictionary<string, ${type}> { ${Object.entries(o).map(([k, v]) => `[${str(k)}] = ${f(v)}`).join(", ")} }`;

// One writer per export of data.js, in the order they're written. Any export not listed here is an error.
const writers = {
  W: v => `public const double W = ${num(v)};`,
  H: v => `public const double H = ${num(v)};`,
  W_MAX: v => `public const double W_MAX = ${num(v)};`,
  LANES: v => `public static readonly double[] LANES = { ${list(v, num)} };`,
  TOP: v => `public const double TOP = ${num(v)};`,
  BOTTOM: v => `public const double BOTTOM = ${num(v)};`,
  CALLS: v => `public static readonly CallDef[] CALLS =\n        {\n${v.map(c => {
    keys(c, ["t", "who", "n", "v", "date", "home"], "CALLS");
    return `            new CallDef(${num(c.t)}, ${str(c.who)}, ${int(c.n)}, ${num(c.v)}, ${str(c.date)}, ${c.home === true}),`;
  }).join("\n")}\n        };`,
  START_DATE: v => `public const string START_DATE = ${str(v)};`,
  QUIET_DATES: v => `public static readonly (double T, string Date)[] QUIET_DATES = { ${list(v, ([t, d]) => `(${num(t)}, ${str(d)})`)} };`,
  TUNING: v => `public static class TUNING\n        {\n${Object.entries(v).map(([k, n]) => `            public const double ${k} = ${num(n)};`).join("\n")}\n        }`,
  DEFAULT_PILL_W: v => `public static readonly IReadOnlyDictionary<string, double> DEFAULT_PILL_W = ${dict("double", v, num)};`,
  PAPER_WARM: v => `public static readonly int[] PAPER_WARM = { ${list(v, int)} };`,
  PAPER_COLD: v => `public static readonly int[] PAPER_COLD = { ${list(v, int)} };`,
  FOLLOW_UP: v => `public static readonly string[] FOLLOW_UP =\n        {\n${v.map(s => `            ${str(s)},`).join("\n")}\n        };`,
  PENDING: v => `public static readonly string[] PENDING =\n        {\n${v.map(s => `            ${str(s)},`).join("\n")}\n        };`,
  VOICEMAIL: v => `public const string VOICEMAIL = ${str(v)};`,
  LAST_CALL: v => `public const string LAST_CALL = ${str(v)};`,
  CAPTION_HEADERS: v => `public static readonly IReadOnlyDictionary<string, string> CAPTION_HEADERS = ${dict("string", v, str)};`,
  FINAL: v => `public static readonly IReadOnlyDictionary<string, Message> FINAL = new Dictionary<string, Message>\n        {\n${Object.entries(v).map(([k, m]) => {
    keys(m, ["who", "date", "text"], "FINAL");
    return `            [${str(k)}] = new Message(${str(m.who)}, ${str(m.date)}, ${str(m.text)}),`;
  }).join("\n")}\n        };`,
  TURN_BACK: v => `public static readonly IReadOnlyDictionary<string, string[]> TURN_BACK = ${dict("string[]", v, a => `new[] { ${list(a, str)} }`)};`,
  LESSON: v => `public const string LESSON = ${str(v)};`,
  RING: v => {
    keys(v, ["MOTIF", "STEP", "REST", "VOLUME"], "RING");
    return `public static class RING\n        {\n            public static readonly int[] MOTIF = { ${list(v.MOTIF, int)} };\n` +
      `            public const double STEP = ${num(v.STEP)}, REST = ${num(v.REST)}, VOLUME = ${num(v.VOLUME)};\n        }`;
  }
};

export function laterData() {
  keys(D, Object.keys(writers), "data.js");
  const body = Object.entries(writers).map(([name, write]) => {
    if (!(name in D)) throw new Error(`data.js no longer exports ${name}`);
    return "        " + write(D[name]);
  });
  return `// GENERATED by web/later/tools/export-unity.mjs from web/later/src/data.js. Do not edit:
// change data.js, then run \`npm run export-unity\` in web/later.
using System.Collections.Generic;

namespace Later
{
    public static class LaterData
    {
${body.join("\n")}
    }
}
`;
}

// Rounds played by the JavaScript simulation, step by step, for the Unity version to replay and match exactly.
// Inputs are rounded to 3 decimals before the round sees them, so the replay feeds identical numbers.
const q = v => Math.round(v * 1000) / 1000;
const TRACES = [
  { name: "dodge-340", w: 960, dt: 1 / 60, input: r => dodgeTarget(r, 340) },
  { name: "chase-all", w: 960, dt: 1 / 60, input: r => chaseTarget(r) },
  { name: "last-only", w: 960, dt: 1 / 60, input: r => (r.calls[13].spawned ? chaseTarget(r, p => p.ci === 13) : dodgeTarget(r, 340)) },
  { name: "still-long-frames", w: 960, dt: 0.2, input: () => ({ x: 340, y: 302 }) },
  // parked exactly between two lanes from the start (a moon steered there only passes through 85 once), so lane ties matter
  { name: "between-lanes", w: 960, dt: 1 / 60, me: { x: 340, y: 85 }, input: () => ({ x: 340, y: 85 }) },
  { name: "dodge-wide", w: 1169, dt: 1 / 60, input: r => dodgeTarget(r, 1100) },
  { name: "home-drift", w: 1280, dt: 1 / 60, input: r => ({ x: 200, y: 302 + 150 * Math.sin(3 * r.t) }) },
  { name: "keys", w: 1280, dt: 1 / 60, input: () => null, keys: r => ({ x: Math.sign(Math.sin(1.3 * r.t)), y: Math.sign(Math.cos(0.9 * r.t)) }) }
];

function trace({ name, w, dt, me = { x: 220, y: 270 }, input, keys = () => ({ x: 0, y: 0 }) }) {
  const r = createRound(undefined, w);
  Object.assign(r.me, me);
  const out = { name, w, dt, meX: me.x, meY: me.y, tx: [], ty: [], has: [], kx: [], ky: [], events: [], checkpoints: [] };
  for (let step = 0; !r.over; step++) {
    const t = input(r), k = keys(r), target = t && { x: q(t.x), y: q(t.y) };
    out.tx.push(target ? target.x : 0); out.ty.push(target ? target.y : 0); out.has.push(!!target);
    out.kx.push(k.x); out.ky.push(k.y);
    for (const e of stepRound(r, dt, { target, keys: k }))
      out.events.push({ step, type: e.type, pill: e.pill ? e.pill.id : 0, close: !!e.close, date: e.date || "" });
    if (step % 30 === 29 || r.over)
      out.checkpoints.push({ step, t: r.t, x: r.me.x, y: r.me.y, score: r.score, missed: r.missed, hits: r.hits, paperK: r.paperK, pills: r.pills.length });
  }
  return out;
}

const roundTraces = () => JSON.stringify({ traces: TRACES.map(trace) }) + "\n";

const outputs = [
  ["Assets/Later/Scripts/Core/LaterData.g.cs", laterData],
  ["Assets/Later/Tests/EditMode/Fixtures/round-traces.json", roundTraces]
];

let stale = 0;
for (const [path, make] of outputs) {
  const file = repo + path, text = make();
  if (check) {
    let old = null;
    try { old = readFileSync(file, "utf8"); } catch {}
    if (old !== text) { console.log(`stale: ${path}`); stale++; }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
